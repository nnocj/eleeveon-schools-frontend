/**
 * app/lib/excel/excelTypes.ts
 * --------------------------------------------------------------------------
 * ELEEVEON EXCEL — SHARED TYPE CONTRACT
 * --------------------------------------------------------------------------
 *
 * Generic Excel interoperability types used by:
 * - student imports/exports;
 * - attendance imports/exports;
 * - assessment-entry imports/exports;
 * - future finance, teachers, inventory and other spreadsheet workflows.
 *
 * IMPORTANT:
 * This file must remain domain-agnostic.
 * Do not import Student, Attendance, AssessmentEntry, etc. here.
 */

export type ExcelPrimitive =
  | string
  | number
  | boolean
  | Date
  | null
  | undefined;

export type ExcelCellValue = ExcelPrimitive;

export type ExcelRawRow = ExcelCellValue[];

export type ExcelSourceRecord = Record<string, ExcelCellValue>;

export type ExcelMappedRecord = Record<string, unknown>;

export type ExcelRowNumber = number;

/**
 * Zero-based column index inside a worksheet row.
 */
export type ExcelColumnIndex = number;

/**
 * Basic information about a workbook sheet.
 */
export interface ExcelSheetInfo {
  name: string;
  index: number;
  rowCount: number;
  columnCount: number;
  hidden?: boolean;
}

/**
 * Parsed workbook representation used by the shared Excel layer.
 */
export interface ParsedExcelWorkbook {
  fileName?: string;
  sheetNames: string[];
  sheets: ExcelParsedSheet[];
}

/**
 * Parsed worksheet.
 *
 * `rows` contains raw matrix-style values.
 *
 * Example:
 *
 * [
 *   ["Student Name", "Student ID", "Gender"],
 *   ["Ama Mensah", "ST001", "Female"],
 *   ["Kojo Boateng", "ST002", "Male"]
 * ]
 */
export interface ExcelParsedSheet {
  name: string;
  index: number;
  rows: ExcelRawRow[];
  rowCount: number;
  columnCount: number;
}

/**
 * Header discovered from a source spreadsheet.
 */
export interface ExcelSourceColumn {
  /**
   * Zero-based index in the worksheet row.
   */
  index: number;

  /**
   * Header exactly as it appeared in the workbook after safe string conversion.
   */
  header: string;

  /**
   * Normalized form used for automatic matching.
   *
   * Example:
   * "Admission No." -> "admission no"
   */
  normalizedHeader: string;

  /**
   * Excel-style column label.
   *
   * Example:
   * 0 -> A
   * 1 -> B
   * 26 -> AA
   */
  columnLetter: string;
}

/**
 * Supported generic destination field types.
 *
 * Domain-specific layers may add their own interpretation on top.
 */
export type ExcelFieldDataType =
  | "string"
  | "number"
  | "integer"
  | "boolean"
  | "date"
  | "datetime"
  | "email"
  | "phone"
  | "id"
  | "unknown";

/**
 * Generic destination field definition.
 *
 * Example:
 *
 * {
 *   key: "fullName",
 *   label: "Student Name",
 *   aliases: ["student", "name", "full name"],
 *   required: true,
 *   dataType: "string"
 * }
 */
export interface ExcelFieldDefinition {
  key: string;
  label: string;

  /**
   * Alternative source-header names that can map to this field.
   */
  aliases?: string[];

  required?: boolean;

  dataType?: ExcelFieldDataType;

  description?: string;

  /**
   * Allows destination-specific validation without putting domain logic
   * inside the shared Excel layer.
   */
  validate?: (
    value: unknown,
    context: ExcelFieldValidationContext,
  ) => ExcelValidationIssue | ExcelValidationIssue[] | null | undefined;

  /**
   * Allows the destination layer to normalize a cell before validation/import.
   */
  transform?: (
    value: unknown,
    context: ExcelFieldTransformContext,
  ) => unknown;
}

/**
 * Mapping between one source spreadsheet column and one destination field.
 */
export interface ExcelColumnMapping {
  sourceIndex: number;
  sourceHeader: string;
  targetKey: string;
  targetLabel?: string;

  /**
   * 0–1 confidence generated by automatic mapping.
   */
  confidence?: number;

  /**
   * Indicates whether the mapping was suggested automatically.
   */
  automatic?: boolean;
}

/**
 * Mapping suggestion shown before an import is confirmed.
 */
export interface ExcelColumnMappingSuggestion {
  sourceColumn: ExcelSourceColumn;
  targetField?: ExcelFieldDefinition;
  confidence: number;
  reason:
    | "exact"
    | "normalized"
    | "alias"
    | "partial"
    | "none";
}

/**
 * Result of validating the mapping itself.
 */
export interface ExcelMappingValidationResult {
  valid: boolean;
  issues: ExcelValidationIssue[];
  missingRequiredFields: ExcelFieldDefinition[];
  duplicateTargetKeys: string[];
}

/**
 * Severity of an import issue.
 */
export type ExcelValidationSeverity =
  | "error"
  | "warning"
  | "info";

/**
 * Generic issue produced by mapping, parsing or validation.
 */
export interface ExcelValidationIssue {
  code: string;
  message: string;
  severity: ExcelValidationSeverity;

  /**
   * Human worksheet row number.
   * Usually starts at 1, like Excel itself.
   */
  rowNumber?: number;

  /**
   * Zero-based source column index.
   */
  columnIndex?: number;

  sourceHeader?: string;
  targetKey?: string;

  value?: unknown;
}

/**
 * Context supplied to destination field transformation.
 */
export interface ExcelFieldTransformContext {
  rowNumber: number;
  sourceColumn?: ExcelSourceColumn;
  mapping?: ExcelColumnMapping;
  sourceRecord: ExcelSourceRecord;
}

/**
 * Context supplied to field validation.
 */
export interface ExcelFieldValidationContext
  extends ExcelFieldTransformContext {
  mappedRecord: ExcelMappedRecord;
}

/**
 * One processed spreadsheet data row.
 */
export interface ExcelProcessedRow<T = ExcelMappedRecord> {
  /**
   * Human-visible worksheet row number.
   */
  rowNumber: number;

  source: ExcelSourceRecord;
  data: T;

  issues: ExcelValidationIssue[];

  valid: boolean;
}

/**
 * Final validation/import-preparation result.
 */
export interface ExcelValidationResult<T = ExcelMappedRecord> {
  valid: boolean;

  totalRows: number;
  validRows: number;
  invalidRows: number;
  warningRows: number;

  /**
   * All processed worksheet rows.
   *
   * This is intentionally an array because a validation result represents
   * the complete imported dataset, not a single row.
   */
  rows: ExcelProcessedRow<T>[];

  issues: ExcelValidationIssue[];
}

/**
 * Generic options used when turning a worksheet into records.
 */
export interface ExcelReadOptions {
  /**
   * Zero-based index of the header row.
   * Defaults to 0.
   */
  headerRowIndex?: number;

  /**
   * Number of rows after the header row to skip before data begins.
   */
  dataRowOffset?: number;

  /**
   * Ignore rows where every cell is empty.
   * Defaults to true.
   */
  skipEmptyRows?: boolean;

  /**
   * Trim string values.
   * Defaults to true.
   */
  trimStrings?: boolean;
}

/**
 * Result after headers and records have been extracted from a sheet.
 */
export interface ExcelSheetRecords {
  sheetName: string;
  headerRowIndex: number;

  columns: ExcelSourceColumn[];

  /**
   * Records keyed by original source header.
   */
  records: ExcelSourceRecord[];

  /**
   * Actual Excel row number for each record.
   */
  rowNumbers: number[];
}

/**
 * Generic import preparation options.
 */
export interface ExcelValidationOptions {
  /**
   * Treat empty mapped required values as errors.
   */
  validateRequired?: boolean;

  /**
   * Add warnings for values that fail generic type coercion.
   */
  validateTypes?: boolean;

  /**
   * Keys whose values must be unique within the imported file.
   */
  uniqueKeys?: string[];

  /**
   * Whether completely empty mapped rows should be ignored.
   */
  skipEmptyMappedRows?: boolean;
}

/**
 * Generic export column definition.
 */
export interface ExcelExportColumn<T = Record<string, unknown>> {
  key: string;
  header: string;
  width?: number;

  value?: (row: T, index: number) => ExcelCellValue;
}

/**
 * One worksheet definition used when creating a workbook.
 */
export interface ExcelExportSheet<T = Record<string, unknown>> {
  name: string;
  columns: ExcelExportColumn<T>[];
  rows: T[];

  /**
   * Optional informational rows placed above the column headers.
   *
   * Example:
   * [
   *   ["School", "Example School"],
   *   ["Class", "JHS 1A"]
   * ]
   */
  preambleRows?: ExcelRawRow[];

  /**
   * Blank rows between preamble and header.
   */
  preambleSpacing?: number;

  /**
   * Freeze the header row where supported.
   */
  freezeHeader?: boolean;
}

/**
 * Generic workbook export request.
 */
export interface ExcelExportWorkbook {
  fileName: string;
  sheets: ExcelExportSheet<any>[];
}

/**
 * Generic result from a duplicate scan.
 */
export interface ExcelDuplicateGroup {
  key: string;
  value: string;
  rowNumbers: number[];
}
